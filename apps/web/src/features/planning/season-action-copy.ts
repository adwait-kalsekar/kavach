import type { DemoLocale, SeasonAssessment } from "@kavach/contracts";
import { cropNames } from "./planning-copy";
export function localizedAction(
  a: SeasonAssessment,
  action: SeasonAssessment["actions"][number],
  locale: DemoLocale,
) {
  if (locale === "en-IN") return action;
  const mr = locale === "mr-IN",
    crop = cropNames[locale][a.input.crop],
    pre = a.input.stage === "pre-sowing";
  const when = mr ? "कृती करण्यापूर्वी" : "काम करने से पहले";
  let title = action.title,
    detail = action.detail;
  if (action.id === "field-moisture") {
    title = mr
      ? pre
        ? "पेरणीच्या जागेतील ओलावा तपासा"
        : "पिकाजवळील ओलावा तपासा"
      : pre
        ? "बुवाई की जगह की नमी जाँचें"
        : "फसल के पास की नमी जाँचें";
    detail =
      a.input.moisture === "unknown"
        ? mr
          ? "प्रादेशिक पाऊस आणि मातीचा अंदाज तुमच्या शेतातील पुरेसा ओलावा सांगू शकत नाही. शेतात तपासणी करा आणि मातीची खोली स्थानिक तज्ज्ञासोबत समजून घ्या."
          : "क्षेत्रीय बारिश और मिट्टी के मॉडल से आपके खेत की पर्याप्त नमी पता नहीं चलती। खेत में जाँच करें और स्थानीय सलाहकार से मिट्टी की गहराई की पुष्टि करें."
        : mr
          ? `तुम्ही शेत ${a.input.moisture === "dry" ? "कोरडे" : "ओलसर"} असल्याचे सांगितले. हे तुमचे निरीक्षण आहे, उपग्रहाचे मोजमाप नाही. ${crop} पिकाच्या सध्याच्या अवस्थेसाठी त्याचा अर्थ स्थानिक तज्ज्ञाकडून समजून घ्या.`
          : `आपने खेत ${a.input.moisture === "dry" ? "सूखा" : "नम"} बताया है। यह आपका निरीक्षण है, उपग्रह का माप नहीं। ${crop} की वर्तमान अवस्था के लिए इसका अर्थ स्थानीय सलाहकार से समझें।`;
  } else if (action.id === "water-certainty") {
    title = mr
      ? a.input.irrigation === "none"
        ? "या पिकाचा कोरडवाहू पर्याय तपासा"
        : "खात्रीने मिळणारे पाणी तपासा"
      : a.input.irrigation === "none"
        ? "इस फसल का वर्षा आधारित विकल्प जाँचें"
        : "भरोसेमंद पानी की पुष्टि करें";
    detail =
      a.input.irrigation === "unknown"
        ? mr
          ? "सिंचन नाही, मर्यादित आहे की खात्रीचे आहे हे निवडा. जवळचे धरण तुमच्या शेताला पाणी मिळते याचा पुरावा नाही."
          : "चुनें कि सिंचाई उपलब्ध नहीं, सीमित या सुनिश्चित है। पास का जलाशय आपके खेत की पानी तक पहुँच साबित नहीं करता।"
        : a.input.irrigation === "none"
          ? a.cropContext.rainfedWindow
            ? mr
              ? `जिल्ह्याच्या जुन्या योजनेत ${crop} पिकासाठी कोरडवाहू वेळापत्रक आहे. चालू हंगामात तुमचे शेत योग्य असल्याची ही खात्री नाही; स्थानिक तज्ज्ञाशी चर्चा करा.`
              : `जिले की पुरानी योजना में ${crop} का वर्षा आधारित कैलेंडर है। यह इस मौसम में आपके खेत की उपयुक्तता की पुष्टि नहीं है; स्थानीय सलाहकार से चर्चा करें।`
            : mr
              ? `या जिल्ह्याच्या जुन्या तक्त्यात कोरडवाहू ${crop} वेळापत्रक दिलेले नाही. बियाणे किंवा खर्च ठरवण्यापूर्वी स्थानिक पर्याय विचारा.`
              : `इस जिले की पुरानी तालिका में वर्षा आधारित ${crop} कैलेंडर नहीं है। बीज या खर्च तय करने से पहले स्थानीय विकल्प पूछें।`
          : mr
            ? "वापरता येणारे पाणी आणि त्याची वेळ संबंधित व्यक्तीकडून निश्चित करा. पाण्याची तुलना फक्त एका उदाहरणातील पाणी देण्याची आहे; संपूर्ण हंगामाची गरज नाही."
            : "उपयोग योग्य पानी और उसकी उपलब्धता का समय जिम्मेदार व्यक्ति से पक्का करें। पानी की तुलना केवल एक उदाहरणात्मक सिंचाई की है, पूरे मौसम की जरूरत की नहीं।";
  } else if (action.id === "crop-context") {
    title = mr
      ? `${crop} पिकाचा स्थानिक संदर्भ तपासा`
      : `${crop} का स्थानीय संदर्भ जाँचें`;
    detail = !pre
      ? mr
        ? "तुमचे पीक वाढीच्या अवस्थेत आहे. पेरणीचे वेळापत्रक उभ्या पिकाची काळजी कशी घ्यावी हे सांगत नाही. पिकाच्या अवस्थेनुसार सल्ला विचारा."
        : "आपकी फसल बढ़ रही है। बुवाई का कैलेंडर खड़ी फसल की देखभाल की सलाह नहीं है। वर्तमान अवस्था के लिए मार्गदर्शन पूछें."
      : a.input.crop === "sorghum"
        ? mr
          ? "येथील संदर्भ रब्बी ज्वारीचा आहे. खरीप ज्वारीच्या सूचना वेगळ्या असतात. मातीची खोली, पिकाचा उपयोग आणि नवीन स्थानिक शिफारस तपासा."
          : "यहाँ रबी ज्वार का संदर्भ है। खरीफ ज्वार के निर्देश अलग हैं। मिट्टी की गहराई, फसल का उपयोग और नई स्थानीय सिफारिश की पुष्टि करें."
        : mr
          ? "कोरडवाहू आणि बागायती वेळापत्रके वेगळी असतात. जुना स्रोत संदर्भासाठी पाहा; जुन्या तारखा चालू पेरणीची शिफारस म्हणून वापरू नका."
          : "वर्षा आधारित और सिंचित कैलेंडर अलग हैं। पुराना स्रोत संदर्भ के लिए देखें; पुरानी तारीखों को वर्तमान बुवाई की सिफारिश न मानें.";
  } else if (action.id === "current-guidance") {
    title = mr
      ? "नवीन स्थानिक सल्ला निश्चित करा"
      : "ताज़ा स्थानीय सलाह की पुष्टि करें";
    detail = !a.cropContext.bulletin
      ? mr
        ? "या जिल्ह्यासाठी चालू सल्लापत्र या संचात मिळालेले नाही. उपलब्ध वेळापत्रक जुने आहे. स्थानिक कृषी विज्ञान केंद्राकडून पीक आणि अवस्थेनुसार सध्याचा सल्ला मागा."
        : "इस जिले का वर्तमान बुलेटिन इस पैक में उपलब्ध नहीं है। उपलब्ध कैलेंडर पुराना है। स्थानीय कृषि विज्ञान केंद्र से फसल और अवस्था के अनुसार ताज़ा सलाह लें."
      : a.guidanceStatus === "expired-bulletin"
        ? mr
          ? "मिळालेल्या सल्लापत्राची संबंधित मुदत संपली आहे. ते नवीन कामाची तारीख निश्चित करत नाही. जिल्ह्याचे नवीन सल्लापत्र मागा."
          : "उपलब्ध बुलेटिन की संबंधित समयसीमा समाप्त हो चुकी है। इससे नए काम की तारीख तय नहीं होती। जिले का ताज़ा बुलेटिन माँगें."
        : mr
          ? "सल्लापत्राची तारीख आणि पीक-अवस्थेची उपयुक्तता स्थानिक पातळीवर तपासा. ॲपमधील कृषी सूचनांचे स्वतंत्र तज्ज्ञ परीक्षण झालेले नाही."
          : "बुलेटिन की तारीख और फसल-अवस्था की उपयुक्तता स्थानीय स्तर पर जाँचें। ऐप के कृषि निर्देशों की स्वतंत्र विशेषज्ञ समीक्षा नहीं हुई है.";
  }
  return {
    ...action,
    title,
    detail,
    when,
    reason: mr
      ? "जिल्हा, पीक, अवस्था, माती आणि पाण्याची परिस्थिती जुळणे आवश्यक आहे. स्रोत आणि त्याची मुदत तपासा."
      : "जिला, फसल, अवस्था, मिट्टी और पानी की परिस्थिति का मेल जरूरी है। स्रोत और उसकी समयसीमा जाँचें.",
  };
}
